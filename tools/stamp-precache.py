#!/usr/bin/env python3
"""Write web/precache.js from `git ls-files web` (tracked files only; untracked files would 404 on the live site
and silently break SW install). Run before committing; `--check` fails if the file is stale."""
import hashlib, subprocess, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
files = subprocess.check_output(["git", "ls-files", "web"], cwd=root, text=True).split()
skip = {"web/sw.js", "web/precache.js"}
rel = sorted(f[len("web/"):] for f in files if f not in skip)
h = hashlib.sha256()
for r in rel:
    h.update(r.encode()); h.update((root / "web" / r).read_bytes())
ver = h.hexdigest()[:12]
lines = ["// GENERATED by tools/stamp-precache.py from `git ls-files web`. Do not edit.",
         f"self.PRECACHE_VERSION = '{ver}';",
         "self.PRECACHE = [", "  './',"] + [f"  '{r}'," for r in rel] + ["];", ""]
text = "\n".join(lines)
out = root / "web" / "precache.js"
if "--check" in sys.argv:
    if not out.exists() or out.read_text() != text:
        print("precache.js is stale: run tools/stamp-precache.py and git add"); sys.exit(1)
    print("precache ok:", len(rel), "files, version", ver)
else:
    out.write_text(text); print("wrote", out, len(rel), "files, version", ver)
